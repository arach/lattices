// Preserve the original Blink visual system, scoped so its resets, utilities,
// tokens and themes cannot alter the other Lattices pages.
import fs from 'node:fs/promises'
import postcss from 'postcss'
import tailwind from 'tailwindcss'
const source = new URL('../../../products/blink/landing/app/globals.css', import.meta.url)
const css = await fs.readFile(source, 'utf8')
const result = await postcss([tailwind({
  content: ['./src/components/blink/**/*.{ts,tsx}', './src/components/BlinkPage.tsx'],
  theme: { extend: {
    fontFamily: { display: ['var(--font-display)'], text: ['var(--font-text)'], sans: ['var(--font-text)'] },
    colors: { border: 'hsl(var(--border))', background: 'hsl(var(--background))', foreground: 'hsl(var(--foreground))' },
  } },
})]).process(css, { from: source.pathname })
result.root.walkRules(rule => {
  if (rule.parent?.type === 'atrule' && /keyframes$/.test(rule.parent.name)) return
  rule.selectors = rule.selectors.map(selector => {
    let scoped = selector.replace(/:root|\bhtml\b|\bbody\b|:host/g, '#blink-landing')
    scoped = scoped.replace(/\[data-theme="black"\]\s*(?:#blink-landing)?/g, '#blink-landing[data-theme="black"] ')
    return scoped.includes('#blink-landing') ? scoped.trim() : '#blink-landing ' + scoped
  })
})
await fs.writeFile(new URL('../src/styles/blink.generated.css', import.meta.url), '/* Generated by scripts/build-blink-styles.mjs from the Blink landing source. */\n' + result.root.toString())
